function buildQuestionSet(ruleMap) {
  const questions = [];
  for (const [examType, crops] of Object.entries(ruleMap)) {
    for (const [crop, stages] of Object.entries(crops)) {
      for (const [stage, items] of Object.entries(stages)) {
        if (stage === "채종포 2세대") continue;
        for (const [item, answer] of Object.entries(items)) {
          questions.push({
            id: `${examType}__${crop}__${stage}__${item}`,
            examType,
            crop,
            stage,
            item,
            answer: String(answer),
            unit: "%",
            label: `${stage} · ${crop} · ${item}`
          });
        }
      }
    }
  }
  return questions;
}
